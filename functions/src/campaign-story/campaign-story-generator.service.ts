import * as logger from '../utils/logger';
import { GoogleGenAI } from '@google/genai';
import { buildGenerationParams } from '../utils/gemini-config';
import { captureException } from '../utils/sentry-error-handler';
import { buildCampaignStoryPrompt, countWords } from '../prompts/campaign-story-generator.prompt';
import { CampaignStoryFeatureConfig, CampaignStoryInput } from '../types/campaign-story.types';

export interface GeneratedCampaignStory {
  title: string;
  content: string;
  wordCount: number;
}

/** Outside this band the length deserves attention, but we don't retry (tune targetWords instead). */
const WORD_COUNT_WARN_MIN = 400;
const WORD_COUNT_WARN_MAX = 2200;
const DEFAULT_TITLE = 'Het verhaal tot nu toe';

export async function generateCampaignStory(
  sessions: CampaignStoryInput[],
  config: CampaignStoryFeatureConfig
): Promise<GeneratedCampaignStory> {
  const googleAiKey = process.env.GOOGLE_AI_API_KEY;
  if (!googleAiKey) {
    throw new Error('Google AI API key not configured');
  }

  const googleAi = new GoogleGenAI({ apiKey: googleAiKey });
  const prompt = buildCampaignStoryPrompt(sessions, config.targetWords ?? 1200);

  const response = await googleAi.models.generateContent({
    model: config.model,
    contents: [{ role: 'user', parts: [{ text: prompt }] }],
    config: {
      responseMimeType: 'application/json',
      responseSchema: {
        type: 'object' as const,
        properties: {
          title: { type: 'string' as const },
          content: { type: 'string' as const },
        },
        required: ['title', 'content'],
      },
      ...buildGenerationParams(config),
    },
  });

  logger.info('generateCampaignStory: Gemini response received', {
    sessions: sessions.length,
    finishReason: response.candidates?.[0]?.finishReason,
    promptTokenCount: response.usageMetadata?.promptTokenCount,
    candidatesTokenCount: response.usageMetadata?.candidatesTokenCount,
  });

  const story = parseCampaignStoryResponse(response.text);

  if (story.wordCount < WORD_COUNT_WARN_MIN || story.wordCount > WORD_COUNT_WARN_MAX) {
    logger.warn(`generateCampaignStory: word count ${story.wordCount} outside expected range`);
    captureException(new Error(`Campaign story word count out of range: ${story.wordCount}`), {
      wordCount: story.wordCount,
      sessions: sessions.length,
      targetWords: config.targetWords,
    });
  }

  return story;
}

export function parseCampaignStoryResponse(text: string | undefined): GeneratedCampaignStory {
  if (!text?.trim()) {
    throw new Error('No campaign story generated by AI');
  }

  let parsed: { title?: unknown; content?: unknown };
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new Error('Campaign story response is not valid JSON');
  }

  const content = typeof parsed.content === 'string' ? parsed.content.trim() : '';
  if (!content) {
    throw new Error('Campaign story response has no content');
  }

  const title = typeof parsed.title === 'string' && parsed.title.trim() ? parsed.title.trim() : DEFAULT_TITLE;

  return { title, content, wordCount: countWords(content) };
}
