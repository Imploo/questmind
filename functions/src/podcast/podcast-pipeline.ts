import * as logger from '../utils/logger';
import { GoogleGenAI } from '@google/genai';
import { randomUUID } from 'crypto';
import { Bucket } from '@google-cloud/storage';
import { getPodcastScriptPrompt, PodcastKind } from '../prompts/podcast-script-generator.prompt';
import { buildGenerationParams } from '../utils/gemini-config';
import { AIFeatureConfig, PodcastEntry } from '../types/audio-session.types';

/**
 * Shared podcast building blocks, used by the session podcast and the
 * campaign story podcast (ticket #69).
 */

export interface PodcastSegment {
  speaker: 'host1' | 'host2';
  text: string;
}

export interface PodcastScript {
  segments: PodcastSegment[];
  estimatedDuration: number;
}

export interface PodcastScriptSource {
  kind: PodcastKind;
  title: string;
  date?: string;
  body: string;
}

export function upsertPodcast(existing: PodcastEntry[], nextEntry: Partial<PodcastEntry> & { version: number }): PodcastEntry[] {
  const index = existing.findIndex(podcast => podcast?.version === nextEntry.version);
  if (index === -1) {
    return [...existing, nextEntry as PodcastEntry];
  }
  const updated = [...existing];
  updated[index] = { ...existing[index], ...nextEntry } as PodcastEntry;
  return updated;
}

export function parseScriptResponse(text: string): PodcastScript {
  const segments: PodcastSegment[] = [];
  const lines = text.split('\n').filter(line => line.trim());

  for (const line of lines) {
    const trimmedLine = line.trim();
    if (trimmedLine.startsWith('HOST1:')) {
      segments.push({
        speaker: 'host1',
        text: trimmedLine.replace('HOST1:', '').trim()
      });
    } else if (trimmedLine.startsWith('HOST2:')) {
      segments.push({
        speaker: 'host2',
        text: trimmedLine.replace('HOST2:', '').trim()
      });
    }
  }

  const totalWords = segments.reduce((sum, seg) => sum + seg.text.split(/\s+/).length, 0);
  const estimatedDuration = Math.ceil((totalWords / 150) * 60);

  return { segments, estimatedDuration };
}

export function buildPodcastUserPrompt(source: PodcastScriptSource): string {
  if (source.kind === 'campaign') {
    return `CAMPAIGN STORY TITLE: ${source.title}\nGENERATED: ${source.date || 'Unknown'}\n\nCAMPAIGN STORY:\n${source.body}`;
  }
  return `SESSION TITLE: ${source.title}\nSESSION DATE: ${source.date || 'Unknown'}\n\nSESSION STORY:\n${source.body}`;
}

/** Generates a two-host podcast script with the regular podcast settings. */
export async function generatePodcastScript(
  source: PodcastScriptSource,
  scriptConfig: AIFeatureConfig,
  maxCharacters: number
): Promise<PodcastScript> {
  const googleAiKey = process.env.GOOGLE_AI_API_KEY;
  if (!googleAiKey) {
    throw new Error('Google AI API key not configured');
  }

  const googleAi = new GoogleGenAI({ apiKey: googleAiKey });

  const scriptResponse = await googleAi.models.generateContent({
    model: scriptConfig.model,
    contents: [
      {
        role: 'user',
        parts: [{ text: buildPodcastUserPrompt(source) }],
      },
    ],
    config: {
      systemInstruction: getPodcastScriptPrompt(maxCharacters, source.kind),
      ...buildGenerationParams(scriptConfig),
    },
  });

  const scriptText = scriptResponse.text;
  if (!scriptText) {
    throw new Error('No script generated by AI');
  }

  const script = parseScriptResponse(scriptText);

  if (script.segments.length === 0) {
    throw new Error('Failed to parse script segments');
  }

  const totalCharacters = script.segments.reduce((sum, seg) => sum + seg.text.length, 0);
  logger.debug(`Generated script: ${totalCharacters} characters (limit: ${maxCharacters})`);

  return script;
}

/** Uploads a podcast MP3 and returns a token download URL. */
export async function uploadPodcastMp3(
  storage: Bucket,
  storagePath: string,
  audioBuffer: Buffer,
  metadata: Record<string, string>
): Promise<{ audioUrl: string; fileSize: number }> {
  const downloadToken = randomUUID();

  await storage.file(storagePath).save(audioBuffer, {
    metadata: {
      contentType: 'audio/mpeg',
      metadata: {
        firebaseStorageDownloadTokens: downloadToken,
        ...metadata
      }
    }
  });

  const encodedPath = encodeURIComponent(storagePath);
  const audioUrl = `https://firebasestorage.googleapis.com/v0/b/${storage.name}/o/${encodedPath}?alt=media&token=${downloadToken}`;

  return { audioUrl, fileSize: audioBuffer.length };
}
